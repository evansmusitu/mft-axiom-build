-- Runtime integrity invariants for the NEW Studio V0.3 D1 only.
CREATE TRIGGER IF NOT EXISTS v03_assets_active_job
BEFORE INSERT ON assets
WHEN (SELECT state FROM jobs WHERE id=NEW.job_id) NOT IN ('RUNNING','DISPATCHING')
BEGIN SELECT RAISE(ABORT,'ASSET_INSERT_NONACTIVE_JOB'); END;

CREATE TRIGGER IF NOT EXISTS v03_completed_requires_all_assets
BEFORE UPDATE OF state ON jobs
WHEN NEW.state='COMPLETED' AND
 (SELECT COUNT(*) FROM assets WHERE job_id=NEW.id)!=3
BEGIN SELECT RAISE(ABORT,'COMPLETED_JOB_REQUIRES_THREE_ASSETS'); END;

CREATE TRIGGER IF NOT EXISTS v03_completed_job_terminal
BEFORE UPDATE OF state ON jobs
WHEN OLD.state IN ('COMPLETED','FAILED') AND NEW.state<>OLD.state
BEGIN SELECT RAISE(ABORT,'TERMINAL_JOB_IMMUTABLE'); END;

CREATE TRIGGER IF NOT EXISTS v03_completed_asset_immutable_update
BEFORE UPDATE ON assets
WHEN (SELECT state FROM jobs WHERE id=OLD.job_id)='COMPLETED'
BEGIN SELECT RAISE(ABORT,'COMPLETED_ASSET_IMMUTABLE'); END;

CREATE TRIGGER IF NOT EXISTS v03_completed_asset_immutable_delete
BEFORE DELETE ON assets
WHEN (SELECT state FROM jobs WHERE id=OLD.job_id)='COMPLETED'
BEGIN SELECT RAISE(ABORT,'COMPLETED_ASSET_IMMUTABLE'); END;
